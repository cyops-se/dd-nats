package ddmb

import (
	"context"
	"encoding/json"
	"fmt"
	"log"
	"math/rand"
	"net"
	"net/url"
	"strings"
	"sync"
	"time"

	mqtt "github.com/eclipse/paho.golang/paho"
)

const mqttOperationTimeout = 10 * time.Second

type MqttRequestHandle struct {
	id  string
	mch chan *mqtt.PublishReceived
}

type MqttWildcardEntry struct {
	topic   string
	prefix  string
	handler IMessageHandler
}

type MqttMessageBroker struct {
	Error            error
	ConnectionURL    string
	NetCon           net.Conn
	MqttClient       *mqtt.Client
	MqttCon          *mqtt.Connack
	Handlers         map[string]IMessageHandler
	WildcardHandlers []MqttWildcardEntry
	RequestHandles   map[string]MqttRequestHandle
	mutex            sync.Mutex   // guards reconnect, only one reconnect at a time
	lock             sync.RWMutex // guards maps, slices and the client pointer
}

var letters = []rune("abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ")
var randLock sync.Mutex
var rnd = rand.New(rand.NewSource(time.Now().UnixNano()))

func makeid(n int) string {
	randLock.Lock()
	defer randLock.Unlock()

	b := make([]rune, n)
	for i := range b {
		b[i] = letters[rnd.Intn(len(letters))]
	}
	return string(b)
}

func NewMqttBroker() IMessageBroker {
	mb := new(MqttMessageBroker)
	mb.Handlers = make(map[string]IMessageHandler)
	mb.WildcardHandlers = make([]MqttWildcardEntry, 0)
	mb.RequestHandles = make(map[string]MqttRequestHandle)
	return mb
}

func (mb *MqttMessageBroker) client() *mqtt.Client {
	mb.lock.RLock()
	defer mb.lock.RUnlock()
	return mb.MqttClient
}

func (mb *MqttMessageBroker) onPublishReceived(pr mqtt.PublishReceived) (bool, error) {
	topic := pr.Packet.Topic
	responseTopic := ""
	if pr.Packet.Properties != nil {
		responseTopic = pr.Packet.Properties.ResponseTopic
	}

	if strings.HasPrefix(topic, "_INBOX_") {
		// The topic is autogenerated for the response message in req/resp pattern
		mb.lock.Lock()
		requesthandle, ok := mb.RequestHandles[topic]
		if ok {
			delete(mb.RequestHandles, topic)
		}
		mb.lock.Unlock()

		if ok {
			select {
			case requesthandle.mch <- &pr:
			default:
			}
		}

		return true, nil
	}

	mb.lock.RLock()
	handler, ok := mb.Handlers[topic]
	if !ok {
		handler, ok = mb.Handlers["#"]
	}
	if !ok {
		handler, ok = mb.checkWildcard(topic)
	}
	mb.lock.RUnlock()

	if !ok {
		log.Printf("UNHANDLED message received: %s : %s", topic, string(pr.Packet.Payload))
		return true, nil
	}

	// Unfortunately, we have to adapt to the NATS path specification again since all apps must use it
	dispatch(handler, strings.ReplaceAll(topic, "/", "."), responseTopic, pr.Packet.Payload)
	return true, nil
}

func (mb *MqttMessageBroker) Connect(connectionUrl string) error {
	lu, err := url.Parse(connectionUrl)
	if err != nil {
		mb.Error = fmt.Errorf("unable to parse provided URL %s, error: %s", connectionUrl, err)
		log.Println(mb.Error.Error())
		return mb.Error
	}

	mb.ConnectionURL = connectionUrl
	server := lu.Host

	for {
		conn, err := net.Dial("tcp", server)
		if err != nil {
			log.Printf("Failed to connect to MQTT server, retrying in 5 seconds, error: %s", err.Error())
			time.Sleep(5 * time.Second)
			continue
		}

		log.Printf("New client at %s", server)
		client := mqtt.NewClient(mqtt.ClientConfig{
			OnPublishReceived: []func(mqtt.PublishReceived) (bool, error){mb.onPublishReceived},
			OnClientError: func(err error) {
				log.Printf("MQTT client error detected: %s", err.Error())
				if mb.mutex.TryLock() {
					go mb.reconnect()
				}
			},
			OnServerDisconnect: func(d *mqtt.Disconnect) {
				if d.Properties != nil {
					log.Printf("MQTT server requested disconnect: %s", d.Properties.ReasonString)
				} else {
					log.Printf("MQTT server requested disconnect; reason code: %d", d.ReasonCode)
				}
				if mb.mutex.TryLock() {
					go mb.reconnect()
				}
			},
			Conn: conn,
		})

		log.Printf("Connecting %s", server)
		cp := &mqtt.Connect{KeepAlive: 30, CleanStart: false, UsernameFlag: false, PasswordFlag: false}

		ctx, cancel := context.WithTimeout(context.Background(), mqttOperationTimeout)
		ca, err := client.Connect(ctx, cp)
		cancel()

		if err != nil || ca == nil || ca.ReasonCode != 0 {
			reason := "unknown"
			if err != nil {
				reason = err.Error()
			} else if ca != nil && ca.Properties != nil {
				reason = ca.Properties.ReasonString
			} else if ca != nil {
				reason = fmt.Sprintf("reason code %d", ca.ReasonCode)
			}

			log.Printf("Failed to connect to MQTT server, retrying in 5 seconds, error: %s", reason)
			conn.Close()
			time.Sleep(5 * time.Second)
			continue
		}

		mb.lock.Lock()
		mb.NetCon = conn
		mb.MqttClient = client
		mb.MqttCon = ca
		mb.Error = nil
		mb.lock.Unlock()
		break
	}

	log.Printf("Connected to MQTT server: %s", connectionUrl)
	return nil
}

func (mb *MqttMessageBroker) reconnect() {
	defer mb.mutex.Unlock()

	log.Printf("Attempting to reconnect")
	mb.lock.Lock()
	old := mb.MqttClient
	mb.MqttClient = nil
	mb.lock.Unlock()

	if old != nil {
		old.Disconnect(&mqtt.Disconnect{ReasonCode: 0}) // Hopefully cleans up stuff
	}

	if err := mb.Connect(mb.ConnectionURL); err != nil {
		return
	}

	log.Printf("mqtt connection re-established, re-subscribing topics")

	mb.lock.RLock()
	topics := make([]string, 0, len(mb.Handlers)+len(mb.WildcardHandlers))
	for topic := range mb.Handlers {
		topics = append(topics, topic)
	}
	for _, entry := range mb.WildcardHandlers {
		topics = append(topics, entry.topic)
	}
	mb.lock.RUnlock()

	for _, topic := range topics {
		log.Printf("resubscribing topic: %s", topic)
		if err := mb.subscribeTopic(topic); err != nil {
			log.Printf("failed to resubscribe topic: %s, error: %s", topic, err.Error())
		}
	}
}

func (mb *MqttMessageBroker) Disconnect() error {
	client := mb.client()
	if client == nil {
		return nil
	}

	return client.Disconnect(&mqtt.Disconnect{ReasonCode: 0})
}

func (mb *MqttMessageBroker) Publish(topic string, data interface{}) error {
	return mb.PublishWithReponse(topic, "", data)
}

func (mb *MqttMessageBroker) PublishWithReponse(topic string, responseTopic string, data interface{}) error {
	client := mb.client()
	if client == nil {
		return fmt.Errorf("failed to publish message to subject '%s': No connection to MQTT", topic)
	}

	payload, err := toPayload(topic, data, json.Marshal)
	if err != nil {
		return err
	}

	// Make topic MQTT
	topic = strings.ReplaceAll(topic, ".", "/") // As dot '.' is default topic separator, we need to MQTTify it

	pb := &mqtt.Publish{
		Topic:   topic,
		Payload: payload,
		QoS:     0,
	}

	if responseTopic != "" {
		pb.Properties = &mqtt.PublishProperties{ResponseTopic: responseTopic}
	}

	ctx, cancel := context.WithTimeout(context.Background(), mqttOperationTimeout)
	defer cancel()
	_, err = client.Publish(ctx, pb)
	return err
}

// There is no native request/response functions in paho
func (mb *MqttMessageBroker) Request(topic string, data interface{}) ([]byte, error) {
	if mb.client() == nil {
		return nil, fmt.Errorf("failed to publish message to subject '%s': No connection to MQTT", topic)
	}

	id := "_INBOX_" + makeid(32)
	mch := make(chan *mqtt.PublishReceived, 1)

	mb.lock.Lock()
	mb.RequestHandles[id] = MqttRequestHandle{id: id, mch: mch}
	mb.lock.Unlock()

	defer func() {
		mb.lock.Lock()
		delete(mb.RequestHandles, id)
		mb.lock.Unlock()

		if client := mb.client(); client != nil {
			ctx, cancel := context.WithTimeout(context.Background(), mqttOperationTimeout)
			client.Unsubscribe(ctx, &mqtt.Unsubscribe{Topics: []string{id}})
			cancel()
		}
	}()

	if err := mb.subscribeTopic(id); err != nil {
		return nil, fmt.Errorf("failed to subscribe to response topic: %s", err.Error())
	}

	if err := mb.PublishWithReponse(topic, id, data); err != nil {
		return nil, err
	}

	t := time.NewTimer(RequestTimeout)
	defer t.Stop()

	select {
	case pr := <-mch:
		return pr.Packet.Payload, nil
	case <-t.C:
		return nil, fmt.Errorf("request timed out")
	}
}

func (mb *MqttMessageBroker) subscribeTopic(topic string) error {
	client := mb.client()
	if client == nil {
		return fmt.Errorf("no connection to MQTT")
	}

	ctx, cancel := context.WithTimeout(context.Background(), mqttOperationTimeout)
	defer cancel()

	_, err := client.Subscribe(ctx, &mqtt.Subscribe{
		Subscriptions: []mqtt.SubscribeOptions{
			{Topic: topic, QoS: 0, NoLocal: true},
		},
	})

	return err
}

func toMqttTopic(topic string) string {
	topic = strings.ReplaceAll(topic, ".", "/") // As dot '.' is default topic separator, we need to MQTTify it
	topic = strings.ReplaceAll(topic, ">", "#") // As '>' is default remaining path wildcard, we need to MQTTify it
	return topic
}

func (mb *MqttMessageBroker) Subscribe(topic string, callback IMessageHandler) error {
	if mb.client() == nil {
		return fmt.Errorf("failed to subscribe to subject '%s': No connection to MQTT", topic)
	}

	topic = toMqttTopic(topic)
	if err := mb.subscribeTopic(topic); err != nil {
		mb.Error = err
		return err
	}

	mb.lock.Lock()
	defer mb.lock.Unlock()

	if strings.Contains(topic, "#") {
		mb.addWildcard(topic, callback)
		log.Printf("Wildcard subscription added: %s", topic)
	} else {
		if _, ok := mb.Handlers[topic]; !ok {
			mb.Handlers[topic] = callback
		}
		log.Printf("Regular subscription added: %s", topic)
	}

	return nil
}

func (mb *MqttMessageBroker) Unsubscribe(topic string) error {
	topic = toMqttTopic(topic)

	mb.lock.Lock()
	delete(mb.Handlers, topic)
	entries := mb.WildcardHandlers[:0]
	for _, entry := range mb.WildcardHandlers {
		if entry.topic != topic {
			entries = append(entries, entry)
		}
	}
	mb.WildcardHandlers = entries
	mb.lock.Unlock()

	client := mb.client()
	if client == nil {
		return nil
	}

	ctx, cancel := context.WithTimeout(context.Background(), mqttOperationTimeout)
	defer cancel()
	_, err := client.Unsubscribe(ctx, &mqtt.Unsubscribe{Topics: []string{topic}})
	return err
}

// Look through the truncated topics in the wildcard handlers list to see
// if the specified topic matches. Caller must hold mb.lock.
func (mb *MqttMessageBroker) checkWildcard(topic string) (handler IMessageHandler, ok bool) {
	for _, entry := range mb.WildcardHandlers {
		if strings.HasPrefix(topic, entry.prefix) {
			return entry.handler, true
		}
	}

	return handler, false
}

// Adds a handler for a specific prefix topic (wildcard). Caller must hold mb.lock.
func (mb *MqttMessageBroker) addWildcard(topic string, handler IMessageHandler) {
	prefix := strings.Split(topic, "#")[0]
	for _, entry := range mb.WildcardHandlers {
		if entry.topic == topic {
			return
		}
	}

	entry := MqttWildcardEntry{topic: topic, prefix: prefix, handler: handler}
	mb.WildcardHandlers = append(mb.WildcardHandlers, entry)
}
